import { test, expect } from '@playwright/test'
import { mockApi, accountId } from './fixtures'

test('login existente, restauração da sessão e logout real', async ({ page }) => {
  const state = await mockApi(page, { authenticated: false })
  await page.goto('/dashboard')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('E-mail', { exact: true }).fill('paula@example.com')
  await page.getByLabel('Senha', { exact: true }).fill('senha-ficticia')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Configurações', exact: true }).click()
  await expect(page.getByText('paula@example.com')).toBeVisible()
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect(state.requests.some((request) => request.path === '/auth/logout' && request.method === 'POST')).toBeTruthy()
  expect(await page.evaluate(() => localStorage.length)).toBe(0)
  expect(state.unexpected).toEqual([])
  expect(state.runtimeErrors).toEqual([])
})

test('dashboard, busca por documento com debounce, filtros, paginação e detalhes acessíveis', async ({ page }) => {
  const state = await mockApi(page)
  await page.goto('/dashboard')
  await expect(page.getByRole('button', { name: 'Ver detalhes de Maria Fictícia' })).toBeVisible()
  await expect(page.getByText('123.456.789-00', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true })
  await page.getByRole('link', { name: 'Clientes', exact: true }).click()
  await page.getByRole('button', { name: 'Próxima página' }).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(page.getByText('Mostrando 21 a 25 de 25 clientes')).toBeVisible()
  const baseline = state.requests.filter((request) => request.path === '/customers').length
  await page.getByLabel('Buscar cliente', { exact: true }).pressSequentially('123.456.789-00', { delay: 20 })
  await expect(page.getByLabel('Buscar cliente', { exact: true })).toHaveValue('123.456.789-00')
  await expect(page.getByText('Mostrando 1 a 1 de 1 clientes')).toBeVisible()
  expect(state.requests.filter((request) => request.path === '/customers').length - baseline).toBeLessThanOrEqual(2)
  await page.getByRole('button', { name: 'Ver detalhes de Maria Fictícia' }).click()
  const drawer = page.getByRole('dialog', { name: 'Detalhes do cliente' })
  await expect(drawer).toBeVisible()
  await expect(drawer.getByText('123.456.789-00', { exact: true })).toBeVisible()
  await expect(drawer.getByRole('link', { name: 'Abrir no WhatsApp' })).toHaveAttribute('href', 'https://wa.me/5511999999999')
  await expect(drawer.getByRole('link', { name: 'Abrir no WhatsApp' })).toHaveAttribute('rel', 'noopener noreferrer')
  await page.screenshot({ path: 'test-results/customer-drawer.png' })
  await page.keyboard.press('Escape')
  await expect(drawer).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Ver detalhes de Maria Fictícia' })).toBeFocused()
  await page.getByRole('button', { name: 'Limpar', exact: true }).click()
  await page.getByRole('button', { name: 'Sem telefone', exact: true }).click()
  await expect(page.getByText('Mostrando 1 a 12 de 12 clientes')).toBeVisible()
  await expect(page.locator('.customer-table a[href^="https://wa.me/"]')).toHaveCount(0)
  await page.getByLabel('Conta/CNPJ', { exact: true }).selectOption(accountId)
  await expect(page).toHaveURL(new RegExp(`marketplaceAccountId=${accountId}`))
  expect(state.requests.filter((request) => request.path === '/customers' && new URLSearchParams(request.search).get('limit') === '20').every((request) => !new URLSearchParams(request.search).has('platform'))).toBeTruthy()
  expect(state.unexpected).toEqual([])
})

