test('estados vazio, erro recuperável e sessão expirada', async ({ page }) => {
  const state = await mockApi(page, { empty: true })
  state.customerFailures = Infinity
  await page.goto('/customers')
  await expect(page.getByRole('alert')).toBeVisible()
  state.customerFailures = 0
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  await expect(page.getByRole('heading', { name: 'Nenhum cliente encontrado' })).toBeVisible()
  await page.getByRole('link', { name: 'Contas Integradas', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Nenhuma conta conectada' })).toBeVisible()
  state.expired = true
  await page.getByRole('link', { name: 'Clientes', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect(state.unexpected).toEqual([])
})

