test('contas mostram retorno OAuth, confirmam desconexão e iniciam autorização por navegação', async ({ page }) => {
  const state = await mockApi(page)
  await page.goto('/?mercadolivre=success')
  await expect(page).toHaveURL(/\/marketplace-accounts$/)
  await expect(page.getByText('Conta do Mercado Livre conectada com sucesso.')).toBeVisible()
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: 'Desconectar conta', exact: true }).click()
  expect(state.requests.filter((request) => request.method === 'DELETE')).toHaveLength(0)
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Desconectar conta', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Nenhuma conta conectada' })).toBeVisible()
  expect(state.requests.filter((request) => request.method === 'DELETE')).toHaveLength(1)
  await page.getByRole('button', { name: 'Conectar Mercado Livre', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Autorização simulada' })).toBeVisible()
  expect(state.oauthNavigation).toBeTruthy()
  expect(state.unexpected).toEqual([])
  expect(state.runtimeErrors).toEqual([])
})
